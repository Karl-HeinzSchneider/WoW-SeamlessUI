"""Inventory literal defaults and their consumers without loading profiles or frames.

Run from the repository root: python src/audit-defaults.py
The generated inventory is evidence for docs/defaults-audit.md, not a substitute
for tracing dynamic resolvers against the client's source.
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
TOKEN = re.compile(
    r'\s+|--[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|'
    r'-?\d+(?:\.\d+)?|[A-Za-z_]\w*|[^\s]'
)
DECLARATION = re.compile(
    r'\b(defaults|app\.dbDefaults|app\.skinDefaults|app\.positionDefaults|'
    r'lib\.defaults|local RESET|local nativePosition)\s*=\s*(?={)'
)


def table_leaves(source, start):
    tokens = [(m.group(), m.start()) for m in TOKEN.finditer(source, start)
              if not m.group().isspace() and not m.group().startswith('--')]
    index = 0
    leaves = []

    def value(path):
        nonlocal index
        token, offset = tokens[index]
        index += 1
        if token != '{':
            assert token in ('true', 'false', 'nil') or token[0] in "\"'-0123456789", (
                f'Nonliteral default at {source.count(chr(10), 0, offset) + 1}: {token}'
            )
            leaves.append(('.'.join(path), token, offset))
            return
        ordinal = 1
        empty = tokens[index][0] == '}'
        while tokens[index][0] != '}':
            token = tokens[index][0]
            if token == '[':
                key = tokens[index + 1][0].strip("\"'")
                assert tokens[index + 2][0] == ']' and tokens[index + 3][0] == '='
                index += 4
            elif tokens[index + 1][0] == '=':
                key = token
                index += 2
            else:
                key = str(ordinal)
                ordinal += 1
            value(path + [key])
            if tokens[index][0] in (',', ';'):
                index += 1
        index += 1
        if empty:
            leaves.append(('.'.join(path) or '(empty schema)', '{}', offset))

    value([])
    return leaves


def reference(path, line):
    relative = path.relative_to(ROOT).as_posix()
    return f'[{relative}:{line}](../{relative}#L{line})'


def main():
    files = sorted(p for folder in ROOT.glob('Seamless*') if folder.is_dir()
                   for p in folder.rglob('*.lua')
                   if 'lib' not in p.parts and 'locales' not in p.parts)
    # Read-only vendor boundary: the sole embedded feature's authored schema.
    files.append(ROOT / 'Seamless/lib/BetterGroupLoot-1.0/core.lua')
    rows = ['# Defaults source inventory', '',
            'Generated by `python src/audit-defaults.py`. See [audit conclusions](defaults-audit.md).', '',
            'Literal tables below are **authored suite/library data**, not claims about Blizzard defaults.',
            'Schemas declare defaults; preview positions and reset sentinels do not.',
            '`{}` means absent overrides or empty data, not coordinates sampled from a frame.',
            'Preview reset sentinels and observed positions are listed explicitly as such in the audit.', '']
    count = 0
    for path in files:
        source = path.read_text(encoding='utf-8-sig')
        declarations = list(DECLARATION.finditer(source))
        if not declarations:
            continue
        rows += [f'## {path.relative_to(ROOT).as_posix()}', '',
                 '| Declaration / key | Value | Source |', '| --- | --- | --- |']
        for declaration in declarations:
            try:
                leaves = table_leaves(source, declaration.end())
            except AssertionError:
                line = source.count('\n', 0, declaration.start()) + 1
                rows.append(f'| `{declaration[1]}` | Dynamic resolver; see audit | {reference(path, line)} |')
                continue
            for key, value, offset in leaves:
                line = source.count('\n', 0, offset) + 1
                rows.append(f'| `{declaration[1]}.{key}` | `{value}` | {reference(path, line)} |')
                count += 1
        rows.append('')
    rows += ['## Resolver, reset and geometry source index', '',
             'Discovery index for the traced consumers. Geometry setters include authored widget layout,',
             'live display updates and restoration; their arguments must not automatically become defaults.', '',
             '| Source | Declaration / consumer |', '| --- | --- |']
    consumer = re.compile(r'\btooltip\s*=|\bdefault\s*=|function .*\b(?:Default|Reset|GetDefault|GetDefaultSetting)|'
                          r'\b(?:GetOptionDefault|GetCVarOptionInfo|GetDefaultSystemAnchorInfo|'
                          r'GetDefaultSettingForSystem|SetSize|SetWidth|SetHeight|SetScale|SetPoint|'
                          r'SetAllPoints|Point|ResetProfile)\s*\(|module:Edit\(|'
                          r'\bcvar\s*=|\bGetCVar(?:Bool)?\s*\(|\blocal [A-Z_]+.*=')
    for path in files:
        for line, text in enumerate(path.read_text(encoding='utf-8-sig').splitlines(), 1):
            if consumer.search(text) and not text.lstrip().startswith('--'):
                snippet = text.strip().replace('|', '&#124;').replace('`', '&#96;')
                rows.append(f'| {reference(path, line)} | `{snippet}` |')
    rows += ['', '## Authored XML geometry', '',
             '| Source | Component declaration |', '| --- | --- |']
    for folder in sorted(ROOT.glob('Seamless*')):
        if not folder.is_dir():
            continue
        for path in sorted(folder.rglob('*.xml')):
            if 'lib' in path.parts:
                continue
            for line, text in enumerate(path.read_text(encoding='utf-8-sig').splitlines(), 1):
                if re.search(r'<(?:Size|Anchor|FontString)\b', text):
                    rows.append(f'| {reference(path, line)} | `{text.strip()}` |')
    rows += ['', f'Inventory: {count} literal leaves / empty tables across {len(files)} Lua source files scanned.', '']
    output = ROOT / 'docs/defaults-inventory.md'
    output.write_text('\n'.join(rows), encoding='utf-8')
    print(f'{count} literal default leaves inventoried in {output}')


if __name__ == '__main__':
    main()
